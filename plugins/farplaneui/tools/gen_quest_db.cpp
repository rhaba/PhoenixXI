/**
 * Builds src/data/quest_db.hpp (quest steps compiled into FarplaneUI) from the questtracker addon's
 * data: data/quests.lua (generated from PhoenixXI's LandSandBoat quest scripts, GPL-3.0) with the
 * hand-written data/overrides_jobs.lua and data/overrides.lua applied (overrides wins).
 *
 *   cl /std:c++latest /EHsc /I..\src gen_quest_db.cpp ..\src\luatable.cpp
 *   gen_quest_db.exe <questtracker\data dir> <out quest_db.hpp>
 */
#include "luatable.hpp"

#include <cstdio>
#include <fstream>
#include <map>
#include <string>
#include <vector>

using namespace farplaneui;

namespace
{
    struct Step
    {
        std::string text, zone, grid;
        int ki{0};
        std::vector<std::pair<int, int>> ev;
        std::vector<std::tuple<int, int, std::string>> need;
        std::vector<std::pair<int, std::string>> needKi;
    };
    struct Quest
    {
        int id{0}, log{0};
        std::string key, name, npc, zone, grid, note;
        std::vector<Step> steps;
    };
    auto ReadStep(const lua::Value& s) -> Step
    {
        Step st;
        st.text = s["text"].Str(), st.zone = s["zone"].Str(), st.grid = s["grid"].Str(), st.ki = s["ki"].Int(0);
        for (size_t i = 1; i <= s["ev"].Size(); ++i)
            st.ev.emplace_back(s["ev"][static_cast<long long>(i)][1LL].Int(), s["ev"][static_cast<long long>(i)][2LL].Int());
        for (size_t i = 1; i <= s["need"].Size(); ++i)
        {
            const auto& n = s["need"][static_cast<long long>(i)];
            st.need.emplace_back(n[1LL].Int(), n[2LL].Int(1), n[3LL].Str());
        }
        for (size_t i = 1; i <= s["needKi"].Size(); ++i)
        {
            const auto& n = s["needKi"][static_cast<long long>(i)];
            st.needKi.emplace_back(n[1LL].Int(), n[2LL].Str());
        }
        return st;
    }
    auto C(const std::string& s) -> std::string
    {
        std::string o = "\"";
        for (const unsigned char c : s)
        {
            if (c == '"' || c == '\\')
                o += '\\', o += static_cast<char>(c);
            else if (c == '\n')
                o += "\\n";
            else if (c < 0x20 || c >= 0x7F)
            {
                char b[8]{};
                std::snprintf(b, sizeof(b), "\\x%02X\"\"", c); // split so following hex digits don't join
                o += b;
            }
            else
                o += static_cast<char>(c);
        }
        return o + "\"";
    }
} // namespace

int main(int argc, char** argv)
{
    if (argc < 3)
    {
        std::printf("usage: gen_quest_db <questtracker data dir> <out hpp>\n");
        return 1;
    }
    const std::string dir = std::string(argv[1]) + "\\";
    std::string err;
    const lua::Value root = lua::ParseFile(dir + "quests.lua", &err);
    if (!root.IsTable())
    {
        std::printf("quests.lua: %s\n", err.c_str());
        return 1;
    }
    std::map<int, Quest> qs;
    std::map<std::string, int> byKey;
    for (const auto& [id, q] : root.tab->indexed)
    {
        Quest o;
        o.id = static_cast<int>(id), o.log = q["log"].Int(static_cast<int>(id / 1000));
        o.key = q["key"].Str(), o.name = q["name"].Str();
        o.npc = q["start"]["npc"].Str(), o.zone = q["start"]["zone"].Str(), o.grid = q["start"]["grid"].Str();
        for (size_t i = 1; i <= q["steps"].Size(); ++i)
            o.steps.push_back(ReadStep(q["steps"][static_cast<long long>(i)]));
        byKey[o.key] = o.id;
        qs[o.id]     = std::move(o);
    }
    int applied = 0;
    for (const char* f : {"overrides_jobs.lua", "overrides.lua"})
    {
        const lua::Value ov = lua::ParseFile(dir + f);
        if (!ov.IsTable())
            continue;
        for (const auto& [key, o] : ov.tab->named)
        {
            const auto k = byKey.find(key);
            if (k == byKey.end())
                continue;
            Quest& q = qs[k->second];
            ++applied;
            if (o["note"].type == lua::Value::Type::String)
                q.note = o["note"].Str();
            if (o["replace"].IsTable())
            {
                q.steps.clear();
                for (size_t i = 1; i <= o["replace"].Size(); ++i)
                    q.steps.push_back(ReadStep(o["replace"][static_cast<long long>(i)]));
            }
            else if (o["steps"].IsTable())
                for (const auto& [i, text] : o["steps"].tab->indexed)
                    if (i >= 1 && static_cast<size_t>(i) <= q.steps.size())
                        q.steps[static_cast<size_t>(i - 1)].text = text.Str();
        }
    }

    std::ofstream out(argv[2], std::ios::binary);
    out << "// Generated by tools/gen_quest_db.cpp from the questtracker addon's data (quests.lua, generated from\n"
           "// PhoenixXI's LandSandBoat quest scripts, GPL-3.0; hand-written overrides by Spongeh). Do not edit by hand.\n"
           "#pragma once\n\nnamespace farplaneui::data\n{\n"
           "    struct QuestEv { int zone, cs; };\n"
           "    struct QuestNeed { int id, qty; const char* name; };\n"
           "    struct QuestNeedKi { int id; const char* name; };\n"
           "    struct QuestStep { const char *text, *zone, *grid; int ki; int ev0, evN, need0, needN, needKi0, needKiN; };\n"
           "    struct QuestDef { int id, log; const char *key, *name, *npc, *zone, *grid, *note; int step0, stepN; };\n\n";
    std::vector<std::string> evs, needs, kis, steps, quests;
    for (const auto& [id, q] : qs)
    {
        const size_t s0 = steps.size();
        for (const auto& st : q.steps)
        {
            const size_t e0 = evs.size(), n0 = needs.size(), k0 = kis.size();
            for (const auto& [z, c] : st.ev)
                evs.push_back("{" + std::to_string(z) + ", " + std::to_string(c) + "}");
            for (const auto& [nid, qty, name] : st.need)
                needs.push_back("{" + std::to_string(nid) + ", " + std::to_string(qty) + ", " + C(name) + "}");
            for (const auto& [kid, name] : st.needKi)
                kis.push_back("{" + std::to_string(kid) + ", " + C(name) + "}");
            steps.push_back("{" + C(st.text) + ", " + C(st.zone) + ", " + C(st.grid) + ", " + std::to_string(st.ki) + ", " + std::to_string(e0) + ", " +
                            std::to_string(evs.size() - e0) + ", " + std::to_string(n0) + ", " + std::to_string(needs.size() - n0) + ", " +
                            std::to_string(k0) + ", " + std::to_string(kis.size() - k0) + "}");
        }
        quests.push_back("{" + std::to_string(q.id) + ", " + std::to_string(q.log) + ", " + C(q.key) + ", " + C(q.name) + ", " + C(q.npc) + ", " +
                         C(q.zone) + ", " + C(q.grid) + ", " + C(q.note) + ", " + std::to_string(s0) + ", " + std::to_string(steps.size() - s0) + "}");
    }
    auto emit = [&](const char* type, const char* name, const std::vector<std::string>& v, const char* empty) {
        out << "    inline constexpr " << type << " " << name << "[] = {\n";
        if (v.empty())
            out << "        " << empty << ",\n";
        for (const auto& l : v)
            out << "        " << l << ",\n";
        out << "    };\n";
    };
    emit("QuestEv", "kQuestEvs", evs, "{0, 0}");
    emit("QuestNeed", "kQuestNeeds", needs, "{0, 0, \"\"}");
    emit("QuestNeedKi", "kQuestNeedKis", kis, "{0, \"\"}");
    emit("QuestStep", "kQuestSteps", steps, "{\"\", \"\", \"\", 0, 0, 0, 0, 0, 0, 0}");
    emit("QuestDef", "kQuests", quests, "{0, 0, \"\", \"\", \"\", \"\", \"\", \"\", 0, 0}");
    out << "} // namespace farplaneui::data\n";
    std::printf("%zu quests, %zu steps, %d overrides -> %s\n", qs.size(), steps.size(), applied, argv[2]);
    return 0;
}

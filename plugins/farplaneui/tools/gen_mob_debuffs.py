"""Builds src/data/mob_debuffs.hpp (debuffs on monsters: what each action applies and for how long) from the enemybar
addon's handlers/database/debuff_retail.lua (GPL-3.0, from mousseng's XITools; spell / WS / JA / pet data from XIUI
tables plus LandSandBoat scripts).

    python tools/gen_mob_debuffs.py <enemybar>/handlers/database/debuff_retail.lua src/data/mob_debuffs.hpp

Weapon skill durations are taken at 1000 TP (enemybar assumes the same: TP is already spent when the action arrives).
"""
import re
import sys

src, out = sys.argv[1], sys.argv[2]
text = open(src, encoding='utf-8').read()

# Section name -> action categories it applies to (0x028 category; 0 = by status id, additional effects).
SECTIONS = {'spells': [4], 'weaponSkills': [3], 'jaPhysical': [3, 6], 'ja': [6, 14, 15], 'pet': [11, 13]}


def section(name):
    m = re.search(r'durations\.' + name + r'\s*=\s*\{(.*?)\n\};', text, re.S)
    return m.group(1) if m else ''


def num(body, key):
    m = re.search(r'\b' + key + r'\s*=\s*(-?\d+)', body)
    return int(m.group(1)) if m else None


entry = re.compile(r'\[(\d+)\]\s*=\s*\{(.*?)\}\s*,?\s*(?:--[^\n]*)?(?=\n|\s*\[)', re.S)
rows = []
for name, cats in SECTIONS.items():
    for m in entry.finditer(section(name)):
        aid, body = int(m.group(1)), m.group(2)
        dur = num(body, 'duration')
        tp = re.search(r'tpDuration\s*=\s*\{([^}]*)\}', body)
        if dur is None and tp:
            b = tp.group(1)
            base = num(b, 'base') or 0
            extra = (num(b, 'per1000Tp') or 0) + (num(b, 'per500Tp') or 0) * 2 + (num(b, 'per200Tp') or 0) * 5 + (num(b, 'per100Tp') or 0) * 10
            dur = base + extra
        if dur is None and 'tpPer500' in body:
            dur = (num(body, 'tpPer500') or 1) * 2
        if dur is None:
            continue
        buff = num(body, 'buffId') or num(body, 'displayBuffId') or 0
        dmg = 'applyOnDamage = true' in body
        clears = re.search(r'clearsBuffs\s*=\s*\{(\d+)', body)
        for c in cats:
            rows.append((c, aid, dur, buff, 1 if dmg else 0, int(clears.group(1)) if clears else 0))

ae = [(int(m.group(1)), num(m.group(2), 'duration')) for m in entry.finditer(section('additionalEffect'))]
ae = [(b, d) for b, d in ae if d is not None]

with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// Generated by tools/gen_mob_debuffs.py from enemybar handlers/database/debuff_retail.lua (GPL-3.0,\n')
    f.write("// mousseng's XITools; data from XIUI tables plus LandSandBoat scripts). Do not edit by hand.\n")
    f.write('#pragma once\n#include <cstdint>\n\nnamespace farplaneui::mobfx\n{\n')
    f.write('    struct ActionDebuff\n    {\n        uint8_t category;  // 0x028 action category\n        uint16_t action;   // spell / WS / ability id\n')
    f.write('        uint16_t seconds;  // base duration\n        uint16_t buff;     // status it applies (0: the one the message names)\n')
    f.write('        uint8_t onDamage;  // applied by the damage message (Dia / Bio / helix)\n        uint16_t clears;   // status it overwrites\n    };\n')
    f.write('    inline constexpr ActionDebuff kActions[] = {\n')
    for r in rows:
        f.write('        {%d, %d, %d, %d, %d, %d},\n' % r)
    f.write('    };\n    struct EffectDuration\n    {\n        uint16_t buff, seconds;\n    };\n')
    f.write('    // Additional effects (en-spells, weapon procs), by status.\n    inline constexpr EffectDuration kAdditional[] = {\n')
    for b, d in ae:
        f.write('        {%d, %d},\n' % (b, d))
    f.write('    };\n} // namespace farplaneui::mobfx\n')
print(len(rows), 'action rows,', len(ae), 'additional effects')
